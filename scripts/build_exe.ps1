# Python 설치 없이 돌아가는 실행 파일을 만든다.
#
#   powershell -ExecutionPolicy Bypass -File scripts\build_exe.ps1
#
# 결과물은 dist\MerAlarm\ 폴더에 만들어지고, 같은 이름의 zip 으로도 묶인다.

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

$python = ".\.venv\Scripts\python.exe"
if (-not (Test-Path $python)) { throw "가상환경이 없습니다. 먼저 scripts\setup.ps1 을 실행하세요." }

& $python -m PyInstaller --version 2>$null | Out-Null
if ($LASTEXITCODE -ne 0) {
    Write-Output "PyInstaller 를 설치합니다..."
    & $python -m pip install pyinstaller --quiet
}

Write-Output "== 이전 결과물 정리 =="
foreach ($d in @("build", "dist")) {
    if (Test-Path $d) { Remove-Item $d -Recurse -Force }
}

Write-Output "== 실행 파일 만들기 (몇 분 걸립니다) =="
# 콘솔을 남긴다. 설정 마법사가 물어보려면 입력창이 있어야 하고,
# 로그가 흐르는 게 보이는 편이 처음 쓰는 사람에게 안심이 된다.
& $python -m PyInstaller `
    --onefile `
    --console `
    --name MerAlarm `
    --hidden-import "pystray._win32" `
    --collect-submodules mercapi `
    --collect-submodules meralarm `
    --collect-submodules discord `
    --noconfirm `
    --clean `
    main.py

if ($LASTEXITCODE -ne 0) { throw "빌드에 실패했습니다." }

Write-Output "== 함께 넣을 파일 챙기기 =="
$out = "dist\MerAlarm"
New-Item -ItemType Directory $out -Force | Out-Null
Move-Item "dist\MerAlarm.exe" "$out\MerAlarm.exe" -Force

# 사용자가 직접 고칠 수 있어야 하므로 exe 안에 넣지 않고 옆에 둔다.
#
# config.yaml 은 **일부러 넣지 않는다.** 넣어두면 새 버전을 받아 같은 폴더에
# 덮어쓸 때 그동안 쌓아온 키워드가 통째로 날아간다. 받는 사람은 exe 만 바꾸려던
# 것이라 그런 일이 벌어지는 줄 모른다. 처음 켤 때 프로그램이 예시본에서 만든다.
Copy-Item "config.example.yaml" "$out\config.example.yaml"

# --setup 은 명령줄 옵션이라 더블클릭으로는 실행할 수 없다. 설정을 다시 하거나
# 디스코드를 연결하려는 사람이 명령 프롬프트를 열게 만들 수는 없으므로 배치 파일로 싼다.
#
# 배치 파일은 줄바꿈이 반드시 CRLF 여야 한다. LF 로 두면 cmd 가 줄을 제대로 나누지
# 못해 "MerAlarm.exe 를 찾을 수 없습니다" 로 끝난다. ps1 이나 sh 와 달리 여기만 그렇다.
$bat = @'
@echo off
cd /d "%~dp0"
"%~dp0MerAlarm.exe" --setup
echo.
pause
'@ -replace "`r?`n", "`r`n"
[System.IO.File]::WriteAllText(
    (Join-Path $out "설정 다시하기.bat"), $bat, [System.Text.Encoding]::ASCII)

@"
MerAlarm - 메루카리 키워드 알리미
====================================

처음 쓰실 때
------------
1. 압축을 풀고 MerAlarm.exe 를 두 번 누릅니다.
   (바탕화면이나 문서 폴더처럼 쓰기가 되는 곳에 풀어주세요)
2. 창이 뜨면 안내에 따라 텔레그램 봇을 만들고 토큰을 붙여넣습니다.
3. 끝입니다. 이후로는 알림이 텔레그램으로 옵니다.

3분이면 끝나고, 파일을 직접 고칠 일은 없습니다.

  [!] "Windows의 PC 보호" 창이 뜨면
      개발자 서명이 없는 프로그램이라 나오는 경고입니다.
      "추가 정보" 를 누른 뒤 "실행" 을 누르면 됩니다.

쓰는 법
-------
설정은 봇에게 명령을 보내서 합니다. /help 를 보내보세요.
텔레그램이든 디스코드든 명령은 똑같습니다.

  /add 키워드          감시할 키워드 추가
  /add 키워드 -제외어   그 키워드에서만 특정 단어 빼기
  /list               지금 감시 중인 목록
  /del 번호           빼기
  /exclude            제외어 - 이 말이 있으면 안 알림
  /require            필수 포함어 - 이 말이 없으면 안 알림
  /config             현재 설정 전부 보기
  /set 항목 값         설정 바꾸기
  /pause  /resume     잠시 멈추기 / 다시 시작
  /status             잘 돌고 있는지 확인

여러 낱말로 찾기
  띄어 쓰면 둘 다 들어 있는 상품만 찾습니다.
  메루카리 검색창에 치는 것과 똑같이 동작합니다.

  /add ふもふも 学マス          두 낱말이 다 든 것만
  /add ガンプラ MG -ジャンク     제외어와 같이 써도 됩니다

  [!] 각각 흔한 낱말이어도 함께 든 물건이 없으면 0건이 됩니다.
      「花海佑芽」 120건, 「ふもふも」 119건인데
      「花海佑芽 ふもふも」 는 0건인 식입니다. 고장이 아닙니다.

알림이 안 올 때
  키워드를 넣었는데 계속 조용하면, 프로그램이 이유를 한 번 알려드립니다.
  셋 중 어느 쪽인지에 따라 하실 일이 다릅니다.

  "지금은 살 수 있는 것이 없습니다"
      검색어는 맞는데 지금 다 팔린 경우입니다.
      그냥 두시면 새로 올라오는 순간 알림이 갑니다.

  "검색어를 확인해 주세요"
      판매중도 판매완료도 0건입니다.
      메루카리에서 그대로 쳐서 나오는지 확인해 보세요.

  "조건에 맞는 상품이 없습니다"
      검색은 되는데 제외어나 필수 포함어가 전부 걸러낸 경우입니다.
      /exclude 번호 로 무엇이 걸려 있는지 보세요.

  [!] 검색이 0건이면 /set age 나 /set bump 를 아무리 늘려도 소용없습니다.
      조건은 빼기만 하고 더하기를 못 합니다.

제외어 고치기
  /add 키워드 -제외어 로 넣은 제외어도 나중에 바꿀 수 있습니다.
  지웠다가 다시 넣지 않아도 됩니다.

  [모든 키워드에]
  키워드가 여러 개일 때 같은 말을 하나하나 적지 않아도 됩니다.
  키워드를 새로 넣어도 자동으로 함께 적용됩니다.

  /exclude                    지금 목록 보기
  /exclude add まとめ ジャンク   넣기 (여러 개 한 번에)
  /exclude del まとめ           빼기

  [한 키워드에만]  번호는 /list 에 나온 번호입니다.

  /exclude 2                  2번 키워드의 제외어 보기
  /exclude 2 add セット         2번 키워드에만 넣기
  /exclude 2 del セット         2번에서 빼기

  넣기 전에 "지금 추적 중인 1,112건 중 37건이 걸립니다" 처럼
  무엇이 사라지는지 먼저 보여드리고 한 번 더 여쭤봅니다.
  전역 제외어는 한 단어만 잘못 넣어도 알림이 통째로 조용해지기 때문입니다.

엉뚱한 상품이 잔뜩 걸릴 때
  제외어로 막아지지 않는 경우가 있습니다.
  메루카리 검색은 제목만 보지 않고 설명문까지 뒤지고,
  짧은 말은 다른 낱말 속에 박혀서도 걸립니다.

  예를 들어 ストレイライト (샤니마스 유닛) 로 찾으면 이런 게 옵니다.

    Stray Kids(ストレイキッズ) ペンライト        <- 아이돌 그룹
    エクストレイル サングラスホルダー             <- 닛산 자동차 부품
    ハイウエストレイヤードデニムパンツ            <- 옷

  실제로 120건 중 제목에 ストレイライト 가 있는 것은 13건뿐이었습니다.
  이럴 때는 제외어로 하나씩 막는 것보다 "있어야 할 말" 을 정하는 게 확실합니다.

  /require 2 add シャニマス アイドルマスター

  제목에 이 중 하나라도 있으면 통과합니다. 전부 있어야 하는 게 아닙니다.

  /require                    전체 목록
  /require 2                  2번 키워드의 필수 포함어
  /require 2 del シャニマス     빼기

  [!] 제외어보다 훨씬 위험합니다.
      제외어는 걸리는 것만 빼지만, 필수 포함어는 걸리지 않는 것을 전부 뺍니다.
      한 글자만 틀려도 그 키워드가 통째로 조용해집니다.
      그래서 넣기 전에 무엇만 남는지 보여드리고 한 번 더 여쭤봅니다.

제외어는 글자 모양을 가리지 않습니다
  대소문자도, 전각/반각도 같은 글자로 봅니다. 아무렇게나 적으셔도 됩니다.

    C108 라고 적으면  ->  c108, Ｃ１０８ 도 걸립니다
    B664 라고 적으면  ->  Ｂ664 (전각) 도 걸립니다
    アルター 라고 적으면 -> アルタｰ (반각) 도 걸립니다

  일본 상품명에는 전각 영숫자와 반각 가타카나가 섞여 있어서,
  눈에는 같아 보이는데 안 걸리는 일이 없도록 맞춰 둔 것입니다.

바꿀 수 있는 설정 (/set 만 쳐도 목록이 나옵니다)

  /set interval 60        감시 주기(초)
  /set age 7              출품 7일 이내 상품만
  /set bump 0             끌어올린 상품은 새 매물로 안 침
  /set krw off            원화 환산 끄기
  /set 2 price_max 50000  2번 키워드만 가격 상한
  /set 2 price_max off    해제

age 와 bump 의 차이
  age  = 출품한 지 며칠 됐나
  bump = 출품하고 며칠 뒤에 갱신됐나

  메루카리는 판매자가 상품을 손대면 검색 위로 다시 떠오릅니다.
  그것을 새 매물이라고 알리지 않으려고 bump 를 씁니다.

  5일 전에 올려두고 그대로인 물건   -> age 5, bump 0 (늦게 발견한 새 매물)
  5일 전에 올리고 오늘 끌어올린 물건 -> age 5, bump 5 (이미 있던 물건)

  둘 다 "새 매물 알림"에만 적용됩니다.
  걸러진 상품도 값을 내리면 그때 알려드립니다.

디스코드로도 받고 싶다면
------------------------
"설정 다시하기.bat" 을 두 번 누르면 두 가지 중에 고르라고 물어봅니다.

  웹훅  URL 하나만 붙여넣으면 끝. 알림만 옵니다        (1분, 쉬움)
  봇    알림에 더해 디스코드에서도 명령을 씁니다        (5분)

  ★ 알림만 받으시면 됩니다 -> 웹훅을 고르세요. 훨씬 간단합니다.
    디스코드에서도 /add 같은 명령을 쓰고 싶을 때만 봇이 필요합니다.

디스코드는 무료입니다. 봇을 만들어도 돈이 들지 않습니다.

[웹훅으로 하려면]
1. 알림 받을 채널의 톱니(채널 편집)를 누릅니다
2. 왼쪽 메뉴에서 "연동" -> "웹후크" -> "새 웹후크"
3. "웹후크 URL 복사" 를 누릅니다
4. "설정 다시하기.bat" 에서 2번을 고르고 붙여넣습니다

[봇으로 하려면]
0. 먼저 내 디스코드 서버가 있어야 합니다.
   없으면 디스코드 왼쪽 끝의 "+" -> "직접 만들기" 로 하나 만드세요.
   내가 만든 서버여야 명령을 쓸 수 있습니다.

1. https://discord.com/developers/applications 를 엽니다
   (여기는 화면이 전부 영어입니다. 아래 버튼 이름 그대로 찾으시면 됩니다)
2. 오른쪽 위 "New Application" -> 이름을 짓고 만듭니다
3. 왼쪽 메뉴 "Bot" -> "Reset Token" -> "Yes, do it!"
   -> 나온 긴 글자를 "Copy" 로 복사합니다
4. "설정 다시하기.bat" 에서 3번을 고르고 붙여넣습니다
5. 화면에 긴 주소가 하나 뜹니다. 그것을 복사해 브라우저 주소창에 붙여넣고,
   내 서버를 고른 뒤 "계속하기" -> "승인" 을 누릅니다
6. 알림 받을 채널을 고르면 끝입니다

  [!] "Reset Token" 이 무섭게 보이지만 처음 만들 때는 정상입니다.
      봇을 새로 만들면 토큰이 아직 없어서 한 번 눌러 받아야 합니다.
  [!] 토큰은 그때 한 번만 보입니다. 놓쳤으면 다시 Reset 하면 됩니다.
      (다시 눌러도 봇이 지워지지는 않습니다)
  [!] 봇 토큰은 비밀번호와 같습니다. 남에게 보내지 마세요.
  [!] 5번에서 봇을 초대하지 않으면 아무 일도 일어나지 않습니다.
      봇을 만드는 것과 서버에 넣는 것은 별개입니다. 여기서 많이 놓칩니다.

  [!] 초대한 직후 봇이 회색(오프라인)으로 보이는 것은 정상입니다.
      MerAlarm.exe 를 켜면 초록색으로 바뀝니다.
  [!] 명령은 서버를 만든 사람만 쓸 수 있습니다. 다른 사람이 쳐도
      "주인만 조작할 수 있습니다" 가 뜨고 설정은 바뀌지 않습니다.

봇으로 하면 텔레그램 없이 디스코드만으로도 쓸 수 있습니다.
둘 다 설정하면 알림은 양쪽으로 오고, 명령은 어느 쪽에서 쳐도 됩니다.
한쪽에서 키워드를 넣으면 다른 쪽에도 똑같이 반영됩니다.
(웹훅과 봇을 둘 다 넣어도 알림이 두 번 오지는 않습니다. 봇만 씁니다)

끄는 법
