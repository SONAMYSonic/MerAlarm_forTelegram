"""제목과 제외어를 견줄 때 쓰는 글자 다듬기.

메루카리 제목에는 사람 눈에 같아 보이지만 코드에는 다른 글자가 섞여 있다.

    Ｂ664      전각 영숫자   — 제외어에 B664 라고 적으면 안 걸린다
    ｱｸｽﾀ       반각 가타카나 — アクスタ 로 적으면 안 걸린다
    アルタｰ     반각 장음     — アルター 로 적으면 안 걸린다
    C108/c108  대소문자

`NFKC` 정규화가 앞의 셋을, `casefold` 가 대소문자를 한 모양으로 모아준다. 제목과
제외어 **양쪽에 똑같이** 걸기 때문에 어느 쪽을 어떻게 적어도 서로 걸린다.

실측으로 추적 중인 상품명의 35%가 NFKC 로 모양이 바뀐다(대부분 전각 공백과 괄호).
"""

import unicodedata


def fold(text: str) -> str:
    """비교용으로 다듬은 글자. 보여줄 때는 쓰지 않는다."""
    return unicodedata.normalize("NFKC", text).casefold()
